"""（已移除）切换账号后记录「当前逻辑账号归属」的 sink。

## 为什么删掉

早期版本需要在「切换账号」任务成功后，把目标账号记进状态文件
（`config/balanced_state.json` 的 `current_account` 字段），后续任务才知道
该读写哪个账号的记录。

那条设计有三个问题：

1. **两套账号来源**：文件里的归属 vs `RecordID` 读到的 UID，两者可能不一致，
   于是需要 `account_unsaved` 这种「归属不可信」保护标志，而它只在
   「再次切换账号成功」或「重启 agent」时才能清除 —— 很容易卡住；
2. **手工换号识别不到**：玩家在游戏里直接换号，文件里的归属不会变；
3. **多出的状态维度**：三个进程级标志、两套回落规则，每次 review 都能指出
   一处新的不一致。

现在账号归属**只认游戏内真实 UID**（`RecordID` 在主界面的 OCR 结果，由
`BalancedTaskEntry` 连续采样确认）。没有文件归属、没有回落、没有保护标志，
也就不需要在切换账号后做任何记录。

原版「切换账号」任务本身完全不受影响 —— 它照常切换账号，只是不再有人去
读它的结果。

保留这个空文件是为了让「这个 sink 曾经存在、现在删了」这件事在代码库里
有据可查；`agent/custom/sink/__init__.py` 已不再导入它。
"""

